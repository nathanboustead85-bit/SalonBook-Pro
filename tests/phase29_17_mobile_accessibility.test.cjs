"use strict";
const test=require("node:test"),assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm"),path=require("node:path");
const html=fs.readFileSync(path.join(__dirname,"../web/phase29/onboarding-29-17.html"),"utf8");
const js=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
test("standalone HTML",()=>assert.ok(html.startsWith("<!doctype html>")));
test("JavaScript parses",()=>new vm.Script(js));
test("phase title",()=>assert.ok(html.includes("Phase 29.17")));
test("updated mobile hero",()=>assert.ok(html.includes("Accessible, reliable mobile onboarding")));
test("seven steps",()=>assert.equal((html.match(/<button data-step="/g)||[]).length,7));
test("accessible status",()=>assert.ok(html.includes('id="navigationAnnouncement" role="status"')));
test("polite announcements",()=>assert.ok(html.includes('aria-live="polite" aria-atomic="true"')));
test("screen-reader-only style",()=>assert.ok(html.includes(".sr-only{")));
test("step announcement",()=>assert.ok(js.includes('$("navigationAnnouncement").textContent="Step "')));
test("step index announcement",()=>assert.ok(js.includes('(step+1)+" of 7: "')));
test("focus optional for initial render",()=>assert.ok(js.includes("function show(n,focusPanel=false)")));
test("step buttons focus panels",()=>assert.ok(js.includes('show(Number(b.dataset.step),true)')));
test("back focuses panel",()=>assert.ok(js.includes('show(step-1,true)')));
test("next focuses panel",()=>assert.ok(js.includes('show(step+1,true)')));
test("panel keyboard focusable",()=>assert.ok(js.includes('panel?.setAttribute("tabindex","-1")')));
test("focus without scroll jump",()=>assert.ok(js.includes('panel?.focus({preventScroll:true})')));
test("panel scroll into view",()=>assert.ok(js.includes('panel?.scrollIntoView({block:"start",behavior:"instant"})')));
test("panel focus outline",()=>assert.ok(html.includes("[data-panel]:focus{outline:")));
test("mobile sticky actions",()=>assert.ok(html.includes(".actions{position:sticky;bottom:0")));
test("mobile touch target",()=>assert.ok(html.includes("min-height:48px")));
test("completion summary preserved",()=>assert.ok(html.includes('id="finishedDetails"')));
test("safe restart preserved",()=>assert.ok(html.includes('id="restartConfirm"')));
test("readiness preserved",()=>assert.ok(js.includes("function readiness()")));
test("completion meter preserved",()=>assert.ok(js.includes("function updateCompletion()")));
test("final review preserved",()=>assert.ok(js.includes("function finalChecks()")));
test("publishing disabled",()=>assert.ok(html.includes("Publish business · Disabled")));
test("offline no network or storage",()=>{for(const x of ["fetch(","XMLHttpRequest","localStorage.","sessionStorage.","indexedDB.","firebase.","<script src="])assert.equal(html.includes(x),false,x)});
