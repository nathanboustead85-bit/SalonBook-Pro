"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const {createEndToEndBookingSafetyAudit}=require("../functions/phase1619EndToEndBookingSafetyAudit");
const {prepareBookingStoragePlan}=require("../functions/phase151BookingInfrastructurePreparation");
const {DISABLED}=require("../functions/phase147DisabledAtomicReservation");
const secret="phase1619-server-test-secret-more-than-32";
const input={ownerId:"salonA",key:"request_12345",intent:{serviceId:"cut",staffId:"barber",date:"2026-11-20",time:"10:00"}};
const plan=prepareBookingStoragePlan({...input,secret});
const id="b".repeat(64);
const marker={ownerId:"salonA",requestId:plan.requestId,fingerprint:plan.fingerprint,reservationId:id,state:"COMMITTED_SIMULATION",schemaVersion:1};
const reservation={id,ownerId:"salonA",requestId:plan.requestId,fingerprint:plan.fingerprint,state:"COMMITTED_SIMULATION",schemaVersion:1};
const pair={consistentSnapshot:true,marker,reservation};
const make=readConsistentPair=>createEndToEndBookingSafetyAudit({secret,readConsistentPair});
async function main(){
 let reads=0;
 const good=make(async()=>{reads++;return pair;});
 const clear=await good.audit({requests:[input],batches:[[input],[input]]});
 assert.equal(clear.status,"END_TO_END_READ_ONLY_CHECKS_PASSED");
 assert.equal(clear.checked,3);
 assert.equal(clear.acceptingBookings,false);
 assert.equal(clear.reservationCreated,false);
 assert.equal(clear.legacyAppointmentsUntouched,true);
 const before=reads;
 const collision=await good.audit({requests:[input,{...input,intent:{...input.intent,time:"11:00"}}],batches:[[input]]});
 assert.equal(collision.status,"END_TO_END_MANUAL_REVIEW_REQUIRED");
 assert.equal(collision.stage,"RECOVERY");
 assert.equal(reads,before,"collision must stop all reads");
 const invalid=await good.audit({requests:[input],batches:[]});
 assert.equal(invalid.status,"END_TO_END_INPUT_INVALID");
 assert.equal(reads,before);
 assert.equal((await good.audit({requests:[],batches:[[input]]})).status,"END_TO_END_INPUT_INVALID");
 assert.equal((await good.audit({requests:[input],batches:[Array.from({length:101},()=>input)]})).status,"END_TO_END_INPUT_INVALID");
 const flood=await good.audit({requests:[input],batches:[Array.from({length:100},()=>input)]});
 assert.equal(flood.status,"END_TO_END_MANUAL_REVIEW_REQUIRED");
 assert.equal(flood.stage,"MONITORING");
 const outage=await make(async()=>{throw Error("offline");}).audit({requests:[input],batches:[[input]]});
 assert.equal(outage.stage,"RECOVERY");
 const corrupt=await make(async()=>({...pair,reservation:{...reservation,ownerId:"salonB"}})).audit({requests:[input],batches:[[input]]});
 assert.equal(corrupt.stage,"RECOVERY");
 const absent=await make(async()=>({consistentSnapshot:true,marker:null,reservation:null})).audit({requests:[input],batches:[[input]]});
 assert.equal(absent.status,"END_TO_END_READ_ONLY_CHECKS_PASSED");
 assert.deepEqual(await good.reserve(input),DISABLED);
 const entry=fs.readFileSync(path.join(__dirname,"../functions/index.js"),"utf8");
 const source=fs.readFileSync(path.join(__dirname,"../functions/phase1619EndToEndBookingSafetyAudit.js"),"utf8");
 assert.ok(!entry.includes("phase1619EndToEndBookingSafetyAudit"));
 assert.ok(!source.includes("firebase-admin")&&!source.includes("runTransaction("));
 assert.ok(!JSON.stringify(clear).includes("request_12345"));
 assert.ok(!JSON.stringify(clear).includes("salonA"));
 console.log("PASS Phase 16.19 end-to-end safety, collision, outage, monitoring, booking disabled");
}
main().catch(e=>{console.error(e);process.exitCode=1;});
