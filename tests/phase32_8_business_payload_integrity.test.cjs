"use strict";
const test=require("node:test"),assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path");
const {initializeTestEnvironment,assertSucceeds,assertFails}=require("@firebase/rules-unit-testing");
const {doc,getDoc,setDoc,deleteDoc,Timestamp}=require("firebase/firestore");
const root=path.resolve(__dirname,".."),projectId="demo-boustio-phase32-staging";
const rules=fs.readFileSync(path.join(root,"firestore.rules"),"utf8");
const config=JSON.parse(fs.readFileSync(path.join(root,"firebase.phase32-4.json"),"utf8"));
const uid="phase328owner",other="phase328other";
const live=(overrides={})=>({json:"[]",schemaVersion:1,updatedAt:Timestamp.now(),...overrides});
const profile=(overrides={})=>({businessId:uid,name:"Synthetic Salon",slug:"synthetic-salon",category:"barber",email:"demo@example.test",phone:"",address:"",description:"",acceptingBookings:false,schemaVersion:1,updatedAt:Timestamp.now(),...overrides});
test("Phase 32.8 business data payload integrity using actual Firestore rules",async t=>{
 assert.equal(process.env.GCLOUD_PROJECT,projectId);
 assert.equal(process.env.FIRESTORE_EMULATOR_HOST,"127.0.0.1:18080");
 assert.equal(config.firestore.rules,"firestore.rules");
 assert(!JSON.stringify(config).includes("salonbook-pro-ad5ff"));
 const env=await initializeTestEnvironment({projectId,firestore:{host:"127.0.0.1",port:18080,rules}});
 t.after(async()=>{await env.cleanup()});
 const verified=env.authenticatedContext(uid,{email_verified:true}).firestore();
 const unverified=env.authenticatedContext(uid,{email_verified:false}).firestore();
 const foreign=env.authenticatedContext(other,{email_verified:true}).firestore();
 const anonymous=env.unauthenticatedContext().firestore();
 const service=doc(verified,"users",uid,"liveData","services");
 const staff=doc(verified,"users",uid,"liveData","staff");
 const bookings=doc(verified,"users",uid,"liveData","bookings");
 const business=doc(verified,"users",uid,"business","profile");
 await env.withSecurityRulesDisabled(async ctx=>{
  const db=ctx.firestore();
  await setDoc(doc(db,"businesses",uid,"settings","bookingMode"),{mode:"frozen"});
  await setDoc(doc(db,"users",uid,"business","profile"),profile());
  await setDoc(doc(db,"users",uid,"liveData","services"),live());
  await setDoc(doc(db,"users",uid,"liveData","staff"),live());
  await setDoc(doc(db,"users",uid,"liveData","bookings"),live());
 });
 const deny=(name,ref,data)=>t.test(name,()=>assertFails(setDoc(ref,data)));
 const allow=(name,ref,data)=>t.test(name,()=>assertSucceeds(setDoc(ref,data)));
 await allow("valid services update allowed",service,live());
 await allow("valid staff update allowed",staff,live());
 await deny("schemaVersion 2 rejected",service,live({schemaVersion:2}));
 await deny("schemaVersion string rejected",service,live({schemaVersion:"1"}));
 await deny("schemaVersion null rejected",service,live({schemaVersion:null}));
 await deny("json array rejected",service,live({json:[]}));
 await deny("json object rejected",service,live({json:{}}));
 await deny("json number rejected",service,live({json:5}));
 await deny("json null rejected",service,live({json:null}));
 await deny("updatedAt string rejected",service,live({updatedAt:"2026-11-21"}));
 await deny("updatedAt number rejected",service,live({updatedAt:1}));
 await deny("unexpected admin field rejected",service,live({admin:true}));
 await deny("unexpected ownerId field rejected",service,live({ownerId:other}));
 await deny("missing json rejected",service,{schemaVersion:1,updatedAt:Timestamp.now()});
 await deny("missing timestamp rejected",service,{json:"[]",schemaVersion:1});
 await deny("oversized json rejected",service,live({json:"x".repeat(500001)}));
 await allow("valid 500000-character json field allowed by rule size bound",staff,live({json:"x".repeat(500000)}));
 await deny("unknown liveData document rejected",doc(verified,"users",uid,"liveData","admin"),live());
 await deny("frozen booking data update rejected",bookings,live());
 await t.test("unverified owner cannot write valid services",()=>assertFails(setDoc(doc(unverified,"users",uid,"liveData","services"),live())));
 await t.test("other owner cannot write valid services",()=>assertFails(setDoc(doc(foreign,"users",uid,"liveData","services"),live())));
 await t.test("anonymous cannot write valid services",()=>assertFails(setDoc(doc(anonymous,"users",uid,"liveData","services"),live())));
 await allow("valid profile update allowed with bookings disabled",business,profile({name:"Synthetic Salon Updated"}));
 await deny("profile schemaVersion 2 rejected",business,profile({schemaVersion:2}));
 await deny("profile string schemaVersion rejected",business,profile({schemaVersion:"1"}));
 await deny("profile acceptingBookings true rejected",business,profile({acceptingBookings:true}));
 await deny("profile acceptingBookings string rejected",business,profile({acceptingBookings:"false"}));
 await deny("profile forged businessId rejected",business,profile({businessId:other}));
 await deny("profile unexpected admin flag rejected",business,profile({admin:true}));
 await deny("profile unexpected owner role rejected",business,profile({role:"admin"}));
 await deny("profile name number rejected",business,profile({name:42}));
 await deny("profile name too short rejected",business,profile({name:"ab"}));
 await deny("profile name too long rejected",business,profile({name:"x".repeat(101)}));
 await deny("profile slug too long rejected",business,profile({slug:"x".repeat(51)}));
 await deny("profile email too long rejected",business,profile({email:"x".repeat(255)}));
 await deny("profile description too long rejected",business,profile({description:"x".repeat(2001)}));
 await deny("profile address object rejected",business,profile({address:{city:"Demo"}}));
 await deny("profile updatedAt string rejected",business,profile({updatedAt:"today"}));
 await deny("profile missing businessId rejected",business,((p)=>{delete p.businessId;return p})(profile()));
 await t.test("unverified owner cannot write valid profile",()=>assertFails(setDoc(doc(unverified,"users",uid,"business","profile"),profile())));
 await t.test("other owner cannot write valid profile",()=>assertFails(setDoc(doc(foreign,"users",uid,"business","profile"),profile())));
 await t.test("anonymous cannot write valid profile",()=>assertFails(setDoc(doc(anonymous,"users",uid,"business","profile"),profile())));
 await t.test("owner cannot delete profile",()=>assertFails(deleteDoc(business)));
 await t.test("invalid writes preserve previously accepted business and services records",async()=>{
  const p=await assertSucceeds(getDoc(business));
  const s=await assertSucceeds(getDoc(service));
  assert.equal(p.data().name,"Synthetic Salon Updated");
  assert.equal(p.data().acceptingBookings,false);
  assert.equal(s.data().schemaVersion,1);
  assert.equal(s.data().json,"[]");
 });
});
