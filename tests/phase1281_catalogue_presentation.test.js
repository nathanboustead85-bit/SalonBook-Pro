"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const {preparePublicView}=require("../web/phase1281/cataloguePresentation");
const sample=()=>({schemaVersion:1,slug:"demo-salon",published:true,businessName:"Demo Salon",ownerUid:"private",clients:[{email:"secret@example.com"}],services:[{id:"cut",name:"Haircut",pricePence:2050,durationMinutes:30,published:true},{id:"hidden",name:"Private",pricePence:100,durationMinutes:30,published:false}],staff:[{id:"sam",name:"Sam",active:true,serviceIds:["cut","hidden"]},{id:"off",name:"Off",active:false,serviceIds:["cut"]}]});
const ok=preparePublicView(sample(),"demo-salon");
assert.equal(ok.status,"PUBLIC_VIEW_READY");
assert.equal(ok.bookingEnabled,false);
assert.equal(ok.view.services[0].priceLabel,"£20.50");
assert.equal(ok.view.services.length,1);
assert.deepEqual(ok.view.staff[0].serviceIds,["cut"]);
assert.equal(ok.view.staff.length,1);
assert.equal("ownerUid" in ok.view,false);
assert.equal("clients" in ok.view,false);
assert.ok(Object.isFrozen(ok.view.services[0]));
assert.equal(preparePublicView({...sample(),published:false},"demo-salon").view,null);
assert.equal(preparePublicView(sample(),"other").view,null);
assert.equal(preparePublicView(sample(),"../private").view,null);
const source=fs.readFileSync("web/phase1281/cataloguePresentation.js","utf8");
for(const banned of ["fetch(","XMLHttpRequest","localStorage","sessionStorage","indexedDB","firebase.","WebSocket("])assert.ok(!source.includes(banned),banned);
console.log("PASS Phase 12.81 public catalogue presentation safety");
