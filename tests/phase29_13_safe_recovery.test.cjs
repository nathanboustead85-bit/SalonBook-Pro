"use strict";
const test=require("node:test"),assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm"),path=require("node:path");
const html=fs.readFileSync(path.join(__dirname,"../web/phase29/onboarding-29-13.html"),"utf8");
const script=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
test("offline HTML",()=>assert.ok(html.startsWith("<!doctype html>")));
test("JavaScript parses",()=>new vm.Script(script));
test("seven setup panels",()=>assert.equal((html.match(/<section data-panel="/g)||[]).length,7));
test("seven navigation steps",()=>assert.equal((html.match(/<button data-step="/g)||[]).length,7));
test("confirmation dialog exists",()=>assert.ok(html.includes('<dialog id="restartConfirm"')));
test("dialog has accessible title",()=>assert.ok(html.includes('aria-labelledby="restartTitle"')));
test("dialog has accessible description",()=>assert.ok(html.includes('aria-describedby="restartDescription"')));
test("cancel restart control",()=>assert.ok(html.includes('id="cancelRestart"')));
test("confirm restart control",()=>assert.ok(html.includes('id="confirmRestart"')));
test("restart only opens dialog",()=>assert.ok(script.includes('$("restart").addEventListener("click",()=>{$("restartConfirm").showModal()')));
test("cancel closes dialog",()=>assert.ok(script.includes('$("cancelRestart").addEventListener("click",()=>{$("restartConfirm").close()')));
test("cancel restores restart focus",()=>assert.ok(script.includes('$("restart").focus()')));
test("confirm closes dialog",()=>assert.ok(script.includes('$("confirmRestart").addEventListener("click",()=>{$("restartConfirm").close()')));
test("reset only after confirmation",()=>assert.ok(script.includes('$("restartConfirm").close();resetData();clearInvalid()')));
test("reset restores wizard",()=>assert.ok(script.includes('$("wizard").hidden=false;show(0)')));
test("reset focuses first field",()=>assert.ok(script.includes('$("business").focus()')));
test("warns about clearing temporary data",()=>assert.ok(html.includes("clear your temporary demo changes")));
test("warns appointments unaffected",()=>assert.ok(html.includes("Your Android appointments will not be affected.")));
test("review errors explain fix navigation",()=>assert.ok(script.includes("Use the Fix buttons in the review.")));
test("errors focus feedback",()=>assert.ok(script.includes('$("feedback").focus()')));
test("readiness preserved",()=>assert.ok(script.includes('function readiness()')));
test("smart guidance preserved",()=>assert.ok(script.includes('function guidance()')));
test("publishing disabled",()=>assert.match(html,/disabled[^>]*>Publish business · Disabled/));
test("no network or storage",()=>{for(const x of ["fetch(","XMLHttpRequest","localStorage.","sessionStorage.","indexedDB.","firebase.","<script src=","<iframe","<link "])assert.equal(html.includes(x),false,x)});
