"use strict";
const test=require("node:test"),assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm"),path=require("node:path");
const html=fs.readFileSync(path.join(__dirname,"../web/phase30/booking-30-2.html"),"utf8");
const script=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
const sandbox={document:{getElementById:()=>({addEventListener(){},value:"",textContent:"",hidden:true,disabled:true,replaceChildren(){},append(){},setAttribute(){}}),createElement:()=>({setAttribute(){},addEventListener(){},append(){},className:"",textContent:""})}};
vm.createContext(sandbox);vm.runInContext(script,sandbox);
const evalIn=s=>vm.runInContext(s,sandbox);
test("standalone HTML",()=>assert.match(html,/^<!doctype html>/i));
test("JS syntax valid",()=>new vm.Script(script));
test("phase title",()=>assert.ok(html.includes("Phase 30.2")));
test("premium brand",()=>assert.ok(html.includes("boust<span>io</span>")));
test("barber selector visible",()=>assert.ok(html.includes('id="stylists"')));
test("barber selection heading",()=>assert.ok(html.includes("Choose your barber")));
test("no preference default",()=>assert.equal(evalIn("state.stylist"),"any"));
test("three barber choices",()=>assert.equal(evalIn("stylists.length"),3));
test("no preference label",()=>assert.equal(evalIn("stylists[0].name"),"No preference"));
test("Sam demo",()=>assert.equal(evalIn("stylists[1].name"),"Sam"));
test("Alex demo",()=>assert.equal(evalIn("stylists[2].name"),"Alex"));
test("summary stylist",()=>assert.ok(html.includes('id="sumStylist"')));
test("selected stylist rendered",()=>assert.ok(script.includes('state.stylist===s.id')));
test("date demo slots",()=>assert.equal(evalIn("dates.length"),4));
test("service count preserved",()=>assert.equal(evalIn("services.length"),4));
test("no preference sees all d1 times",()=>{evalIn('state.date="d1";state.stylist="any"');assert.equal(evalIn("availableSlots().length"),4)});
test("Sam sees d1 morning slots",()=>{evalIn('state.stylist="sam"');assert.deepEqual(Array.from(evalIn("availableSlots()")),["09:00","10:30"])});
test("Alex sees d1 afternoon slots",()=>{evalIn('state.stylist="alex"');assert.deepEqual(Array.from(evalIn("availableSlots()")),["13:00","15:30"])});
test("Sam d2 filtered",()=>{evalIn('state.date="d2";state.stylist="sam"');assert.deepEqual(Array.from(evalIn("availableSlots()")),["09:30","11:00"])});
test("Alex d2 filtered",()=>{evalIn('state.date="d2";state.stylist="alex"');assert.deepEqual(Array.from(evalIn("availableSlots()")),["14:00"])});
test("no date yields no times",()=>{evalIn('state.date=null');assert.equal(evalIn("availableSlots().length"),0)});
test("changing barber clears incompatible time",()=>{evalIn('state.date="d1";state.stylist="any";state.time="15:30";chooseStylist("sam")');assert.equal(evalIn("state.time"),null)});
test("changing barber keeps compatible time",()=>{evalIn('state.date="d1";state.stylist="any";state.time="09:00";chooseStylist("sam")');assert.equal(evalIn("state.time"),"09:00")});
test("invalid stylist rejected",()=>{evalIn('state.stylist="sam"');evalIn('chooseStylist("invalid")');assert.equal(evalIn("state.stylist"),"sam")});
test("confirmation requires available slot",()=>assert.ok(script.includes("availableSlots().includes(state.time)")));
test("date change clears time",()=>assert.ok(script.includes("state.date=d.id;state.time=null")));
test("preview includes barber",()=>assert.ok(script.includes('+" with "+')));
test("no booking created",()=>assert.ok(html.includes("No appointment was created.")));
test("no payments",()=>assert.ok(html.includes("no payment is taken")));
test("no personal data transmitted",()=>assert.ok(html.includes("no customer information is saved or transmitted")));
test("no network APIs",()=>{for(const x of ["fetch(","XMLHttpRequest","WebSocket(","EventSource(","sendBeacon(","<script src="])assert.ok(!html.includes(x),x)});
test("no browser persistence",()=>{for(const x of ["localStorage","sessionStorage","indexedDB","document.cookie"])assert.ok(!html.includes(x),x)});
test("no Firebase",()=>assert.ok(!/firebaseConfig|firebase\/app|firebase\.firestore/.test(html)));
test("no form submission",()=>assert.ok(!/<form\b/i.test(html)));
test("mobile breakpoint",()=>assert.ok(html.includes("@media(max-width:760px)")));
test("small phone breakpoint",()=>assert.ok(html.includes("@media(max-width:360px)")));
test("accessible button pressed state",()=>assert.ok(script.includes('setAttribute("aria-pressed"')));
test("accessible confirmation",()=>assert.ok(html.includes('aria-live="polite"')));
test("safe text rendering",()=>assert.ok(!script.includes(".innerHTML")));
test("reduced motion",()=>assert.ok(html.includes("prefers-reduced-motion")));
test("noindex",()=>assert.ok(html.includes("noindex,nofollow")));
