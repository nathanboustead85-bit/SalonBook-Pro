"use strict";
const test=require("node:test"),assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm"),path=require("node:path");
const html=fs.readFileSync(path.join(__dirname,"../web/phase29/onboarding-29-19.html"),"utf8");
const previous=fs.readFileSync(path.join(__dirname,"../web/phase29/onboarding-29-18.html"),"utf8");
const js=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
const prevJs=previous.match(/<script>([\s\S]*?)<\/script>/)?.[1];
test("standalone HTML",()=>assert.ok(html.toLowerCase().startsWith("<!doctype html>")));
test("JavaScript parses",()=>new vm.Script(js));
test("phase title",()=>assert.ok(html.includes("Phase 29.19")));
test("updated hero",()=>assert.ok(html.includes("Premium mobile design polish")));
test("same functional JS as validated phase 29.18",()=>assert.equal(js,prevJs));
test("seven step controls",()=>assert.equal((html.match(/<button data-step="/g)||[]).length,7));
test("brand teal token",()=>assert.ok(html.includes("--boustio-teal:#087e70")));
test("ink token",()=>assert.ok(html.includes("--boustio-ink:#174940")));
test("border token",()=>assert.ok(html.includes("--boustio-border:#d6e8e0")));
test("background gradient",()=>assert.ok(html.includes("linear-gradient(180deg,#edf8f3")));
test("hero visual accent",()=>assert.ok(html.includes(".hero::after{")));
test("hero decorative accent noninteractive",()=>assert.ok(html.includes("pointer-events:none")));
test("card polish",()=>assert.ok(html.includes(".card{transition:box-shadow")));
test("button touch feedback",()=>assert.ok(html.includes(".primary:not(:disabled):active")));
test("step labels wrap",()=>assert.ok(html.includes(".steps button{line-height:1.35;overflow-wrap:anywhere}")));
test("summary text wraps",()=>assert.ok(html.includes(".summary,.readiness,.finalcheck,.finishedsummary{overflow-wrap:anywhere}")));
test("mobile breakpoint",()=>assert.ok(html.includes("@media(max-width:600px)")));
test("small phone breakpoint",()=>assert.ok(html.includes("@media(max-width:380px)")));
test("mobile steps touch target",()=>assert.ok(html.includes(".steps button{min-height:48px}")));
test("mobile action touch target",()=>assert.ok(html.includes(".actions button{flex:1;min-height:50px}")));
test("small phone action spacing",()=>assert.ok(html.includes(".actions{gap:8px}")));
test("completion screen typography",()=>assert.ok(html.includes(".done h2{font-size:24px;line-height:1.2}")));
test("reduced motion support",()=>assert.ok(html.includes("@media(prefers-reduced-motion:reduce){.card,.primary")));
test("reduced motion disables transform",()=>assert.ok(html.includes("transform:none!important")));
test("completion details preserved",()=>assert.ok(html.includes('id="finishedDetails"')));
test("accessible step status preserved",()=>assert.ok(html.includes('id="navigationAnnouncement"')));
test("restart confirmation preserved",()=>assert.ok(html.includes('id="restartConfirm"')));
test("review errors preserved",()=>assert.ok(js.includes("function finalChecks()")));
test("booking validation preserved",()=>assert.ok(js.includes("function validate()")));
