"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const {classify}=require("../scripts/phase1736_workflow_reference.js");
const repository="nathanboustead85-bit/SalonBook-Pro";
const env="boustio-function-deployment";
const ref="refs/heads/milestone-customer-booking-experience";
const wf=repository+"/.github/workflows/boustio-phase-1736-workflow-reference.yml@"+ref;
const claims={repository,ref,environment:env,job_workflow_ref:wf,workflow_ref:wf};
const c=classify("repo:"+wf+":environment:"+env,claims);
assert.equal(c.valid,true);
assert(c.matches.includes("JOB_WORKFLOW_REF"));
assert(c.matches.includes("WORKFLOW_REF"));
assert.equal(c.containsWorkflowPath,true);
assert.equal(c.containsAtRef,true);
assert.equal(c.environmentMatches,true);
assert.equal(classify("repo:unknown:environment:"+env,claims).matches.length,0);
assert.equal(classify("invalid",claims).valid,false);
const y=fs.readFileSync(".github/workflows/boustio-phase-1736-workflow-reference.yml","utf8");
assert.match(y,/environment: boustio-function-deployment/);
assert.match(y,/CHECK_WORKFLOW_REFERENCE/);
assert.match(y,/id-token: write/);
assert.match(y,/github\.ref == 'refs\/heads\/milestone-customer-booking-experience'/);
assert.doesNotMatch(y,/gcloud|firebase deploy|google-github-actions\/auth/);
console.log("PASS Phase 17.36 workflow reference classification and safeguards");
