"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const {createRecoveryFailureMonitor}=require("../functions/phase1616RecoveryFailureMonitor");
const {prepareBookingStoragePlan}=require("../functions/phase151BookingInfrastructurePreparation");
const {DISABLED}=require("../functions/phase147DisabledAtomicReservation");
const secret="phase1616-server-test-secret-more-than-32";
const input={ownerId:"salonA",key:"request_12345",intent:{serviceId:"cut",staffId:"barber",date:"2026-11-20",time:"10:00"}};
const plan=prepareBookingStoragePlan({...input,secret});
const id="b".repeat(64);
const marker={ownerId:"salonA",requestId:plan.requestId,fingerprint:plan.fingerprint,reservationId:id,state:"COMMITTED_SIMULATION",schemaVersion:1};
const reservation={id,ownerId:"salonA",requestId:plan.requestId,fingerprint:plan.fingerprint,state:"COMMITTED_SIMULATION",schemaVersion:1};
const pair={consistentSnapshot:true,marker,reservation};
const make=readConsistentPair=>createRecoveryFailureMonitor({secret,readConsistentPair});
async function main(){
 const good=make(async()=>pair);
 const clear=await good.monitor([input]);
 assert.equal(clear.status,"MONITOR_READ_ONLY_CLEAR");
 assert.equal(clear.severity,"NONE");
 assert.equal(clear.uncertainCount,0);
 assert.equal((await good.monitor([])).status,"MONITOR_INVALID");
 assert.equal((await good.monitor(Array.from({length:101},()=>input))).status,"MONITOR_INVALID");
 assert.equal((await good.monitor("bad")).status,"MONITOR_INVALID");
 const repeat=await good.monitor(Array.from({length:20},()=>input));
 assert.equal(repeat.status,"MONITOR_MANUAL_REVIEW_REQUIRED");
 assert.equal(repeat.severity,"HIGH");
 assert.equal(repeat.throttled,10);
 assert.equal(repeat.inspected,10);
 const offline=await make(async()=>{throw Error("offline");}).monitor([input]);
 assert.equal(offline.severity,"REVIEW");
 assert.equal(offline.uncertainCount,1);
 assert.equal((await make(async()=>({...pair,marker:null})).monitor([input])).status,"MONITOR_MANUAL_REVIEW_REQUIRED");
 assert.equal((await make(async()=>({...pair,reservation:{...reservation,ownerId:"salonB"}})).monitor([input])).status,"MONITOR_MANUAL_REVIEW_REQUIRED");
 assert.equal((await make(async()=>({...pair,consistentSnapshot:false})).monitor([input])).status,"MONITOR_MANUAL_REVIEW_REQUIRED");
 assert.equal((await make(async()=>({consistentSnapshot:true,marker:null,reservation:null})).monitor([input])).status,"MONITOR_READ_ONLY_CLEAR");
 assert.equal((await good.monitor([{...input,key:"bad"}])).status,"MONITOR_MANUAL_REVIEW_REQUIRED");
 assert.deepEqual(await good.reserve(input),DISABLED);
 const entry=fs.readFileSync(path.join(__dirname,"../functions/index.js"),"utf8");
 const source=fs.readFileSync(path.join(__dirname,"../functions/phase1616RecoveryFailureMonitor.js"),"utf8");
 assert.ok(!entry.includes("phase1616RecoveryFailureMonitor"));
 assert.ok(!source.includes("firebase-admin")&&!source.includes("runTransaction("));
 assert.ok(!JSON.stringify(repeat).includes("request_12345"));
 assert.ok(!JSON.stringify(repeat).includes("salonA"));
 console.log("PASS Phase 16.16 failure monitoring, severity, throttling, outage/corruption isolation, disabled bookings");
}
main().catch(e=>{console.error(e);process.exitCode=1;});
