"use strict";
const test=require("node:test"),assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path");
const {initializeTestEnvironment,assertSucceeds,assertFails}=require("@firebase/rules-unit-testing");
const {doc,getDoc,setDoc,deleteDoc,collection,getDocs,Timestamp}=require("firebase/firestore");
const root=path.resolve(__dirname,".."),projectId="demo-boustio-phase32-staging";
const cfg=JSON.parse(fs.readFileSync(path.join(root,"web/phase32/firebase.emulator-32-4.json"),"utf8"));
const rules=fs.readFileSync(path.join(root,"firestore.rules"),"utf8");
test("Phase 32.4 real production rules: isolated business-owner authorization",async t=>{
 assert.equal(process.env.FIRESTORE_EMULATOR_HOST,"127.0.0.1:18080");
 assert.equal(process.env.GCLOUD_PROJECT,projectId);
 assert.equal(cfg.firestore.rules,"../../firestore.rules");
 assert.equal(cfg.emulators.firestore.host,"127.0.0.1");
 assert.equal(cfg.emulators.auth.host,"127.0.0.1");
 assert(!JSON.stringify(cfg).includes("salonbook-pro-ad5ff"));
 const env=await initializeTestEnvironment({projectId,firestore:{host:"127.0.0.1",port:18080,rules}});
 t.after(async()=>{await env.cleanup()});
 const owner="phase32ownerA",other="phase32ownerB";
 const verified=env.authenticatedContext(owner,{email_verified:true}).firestore();
 const unverified=env.authenticatedContext(owner,{email_verified:false}).firestore();
 const foreign=env.authenticatedContext(other,{email_verified:true}).firestore();
 const anonymous=env.unauthenticatedContext().firestore();
 const profilePath="users/"+owner+"/business/profile";
 const appointmentPath="businesses/"+owner+"/appointments/synthetic";
 const conversationPath="businesses/"+owner+"/conversations/synthetic";
 const livePath="users/"+owner+"/liveData/services";
 const backupPath="users/"+owner+"/backups/latest";
 const bookingPath="users/"+owner+"/customerBookingReservations/synthetic";
 await env.withSecurityRulesDisabled(async context=>{
  const db=context.firestore();
  await setDoc(doc(db,profilePath),{businessId:owner,name:"Synthetic Salon",slug:"synthetic-salon",category:"barber",email:"demo@example.test",phone:"",address:"",description:"",acceptingBookings:false,schemaVersion:1,updatedAt:Timestamp.now()});
  await setDoc(doc(db,appointmentPath),{synthetic:true});
  await setDoc(doc(db,conversationPath),{synthetic:true});
  await setDoc(doc(db,livePath),{json:"[]",schemaVersion:1,updatedAt:Timestamp.now()});
  await setDoc(doc(db,backupPath),{synthetic:true});
  await setDoc(doc(db,bookingPath),{synthetic:true});
  await setDoc(doc(db,"publicBusinesses/synthetic-published"),{published:true,name:"Public Demo"});
  await setDoc(doc(db,"publicBusinesses/synthetic-hidden"),{published:false,name:"Private Demo"});
 });
 const check=async(name,promise,allowed)=>t.test(name,async()=>{if(allowed)await assertSucceeds(promise);else await assertFails(promise)});
 await check("verified owner reads own business profile",getDoc(doc(verified,profilePath)),true);
 await check("unverified owner cannot read business profile",getDoc(doc(unverified,profilePath)),false);
 await check("other verified owner cannot read business profile",getDoc(doc(foreign,profilePath)),false);
 await check("anonymous cannot read business profile",getDoc(doc(anonymous,profilePath)),false);
 await check("verified owner can read own appointments",getDoc(doc(verified,appointmentPath)),true);
 await check("other owner cannot read appointments",getDoc(doc(foreign,appointmentPath)),false);
 await check("unverified owner cannot read appointments",getDoc(doc(unverified,appointmentPath)),false);
 await check("verified owner cannot write appointments directly",setDoc(doc(verified,appointmentPath),{synthetic:false}),false);
 await check("verified owner can read own conversations",getDoc(doc(verified,conversationPath)),true);
 await check("other owner cannot read conversations",getDoc(doc(foreign,conversationPath)),false);
 await check("owner cannot write conversations directly",setDoc(doc(verified,conversationPath),{synthetic:false}),false);
 await check("verified owner can read own live services",getDoc(doc(verified,livePath)),true);
 await check("unverified owner cannot read live services",getDoc(doc(unverified,livePath)),false);
 await check("other owner cannot read live services",getDoc(doc(foreign,livePath)),false);
 await check("owner can read own legacy backup (owner-only rule)",getDoc(doc(unverified,backupPath)),true);
 await check("other owner cannot read backup",getDoc(doc(foreign,backupPath)),false);
 await check("owner cannot read server-only booking reservation",getDoc(doc(verified,bookingPath)),false);
 await check("anonymous cannot read server-only booking reservation",getDoc(doc(anonymous,bookingPath)),false);
 await check("published business is publicly readable",getDoc(doc(anonymous,"publicBusinesses/synthetic-published")),true);
 await check("unpublished business is not publicly readable",getDoc(doc(anonymous,"publicBusinesses/synthetic-hidden")),false);
 await check("public directory cannot be listed",getDocs(collection(anonymous,"publicBusinesses")),false);
 await check("owner cannot delete own business profile",deleteDoc(doc(verified,profilePath)),false);
 await check("owner cannot turn on live booking through profile",setDoc(doc(verified,profilePath),{businessId:owner,name:"Synthetic Salon",slug:"synthetic-salon",category:"barber",email:"demo@example.test",phone:"",address:"",description:"",acceptingBookings:true,schemaVersion:1,updatedAt:Timestamp.now()}),false);
 await check("unverified owner cannot update business profile",setDoc(doc(unverified,profilePath),{businessId:owner,name:"Synthetic Salon",slug:"synthetic-salon",category:"barber",email:"demo@example.test",phone:"",address:"",description:"",acceptingBookings:false,schemaVersion:1,updatedAt:Timestamp.now()}),false);
 await check("cross-owner profile update denied",setDoc(doc(foreign,profilePath),{businessId:owner,name:"Synthetic Salon",slug:"synthetic-salon",category:"barber",email:"demo@example.test",phone:"",address:"",description:"",acceptingBookings:false,schemaVersion:1,updatedAt:Timestamp.now()}),false);
});
