"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const {createRecoveryMonitoringStress}=require("../functions/phase1617RecoveryMonitoringStress");
const {prepareBookingStoragePlan}=require("../functions/phase151BookingInfrastructurePreparation");
const {DISABLED}=require("../functions/phase147DisabledAtomicReservation");
const secret="phase1617-server-test-secret-more-than-32";
const input={ownerId:"salonA",key:"request_12345",intent:{serviceId:"cut",staffId:"barber",date:"2026-11-20",time:"10:00"}};
const plan=prepareBookingStoragePlan({...input,secret});
const id="b".repeat(64);
const marker={ownerId:"salonA",requestId:plan.requestId,fingerprint:plan.fingerprint,reservationId:id,state:"COMMITTED_SIMULATION",schemaVersion:1};
const reservation={id,ownerId:"salonA",requestId:plan.requestId,fingerprint:plan.fingerprint,state:"COMMITTED_SIMULATION",schemaVersion:1};
const pair={consistentSnapshot:true,marker,reservation};
const make=readConsistentPair=>createRecoveryMonitoringStress({secret,readConsistentPair});
async function main(){
 let calls=0,active=0,peak=0;
 const good=make(async()=>{
  calls++;active++;peak=Math.max(peak,active);
  await new Promise(resolve=>setImmediate(resolve));
  active--;return pair;
 });
 const batches=Array.from({length:20},()=>Array.from({length:100},()=>input));
 const stressed=await good.rehearse(batches);
 assert.equal(stressed.status,"STRESS_MANUAL_REVIEW_REQUIRED");
 assert.equal(stressed.batches,20);
 assert.equal(stressed.checked,2000);
 assert.equal(stressed.inspected,200);
 assert.equal(stressed.throttled,1800);
 assert.equal(stressed.uncertainCount,1800);
 assert.equal(stressed.highSeverityBatches,20);
 assert.equal(calls,200);
 assert.ok(peak<=5&&peak>1,"concurrency must stay bounded");
 const clear=await good.rehearse([[input],[input]]);
 assert.equal(clear.status,"STRESS_READ_ONLY_CLEAR");
 assert.equal(clear.uncertainCount,0);
 assert.equal((await good.rehearse([])).status,"STRESS_INPUT_INVALID");
 assert.equal((await good.rehearse([[]])).status,"STRESS_INPUT_INVALID");
 assert.equal((await good.rehearse(Array.from({length:21},()=>[input]))).status,"STRESS_INPUT_INVALID");
 assert.equal((await good.rehearse([Array.from({length:101},()=>input)])).status,"STRESS_INPUT_INVALID");
 assert.equal((await good.rehearse("bad")).status,"STRESS_INPUT_INVALID");
 const offline=await make(async()=>{throw Error("offline");}).rehearse([[input]]);
 assert.equal(offline.status,"STRESS_MANUAL_REVIEW_REQUIRED");
 assert.equal(offline.reviewBatches,1);
 assert.equal((await make(async()=>({...pair,marker:null})).rehearse([[input]])).status,"STRESS_MANUAL_REVIEW_REQUIRED");
 assert.equal((await make(async()=>({...pair,reservation:{...reservation,ownerId:"salonB"}})).rehearse([[input]])).status,"STRESS_MANUAL_REVIEW_REQUIRED");
 assert.equal((await make(async()=>({consistentSnapshot:true,marker:null,reservation:null})).rehearse([[input]])).status,"STRESS_READ_ONLY_CLEAR");
 assert.deepEqual(await good.reserve(input),DISABLED);
 const entry=fs.readFileSync(path.join(__dirname,"../functions/index.js"),"utf8");
 const source=fs.readFileSync(path.join(__dirname,"../functions/phase1617RecoveryMonitoringStress.js"),"utf8");
 assert.ok(!entry.includes("phase1617RecoveryMonitoringStress"));
 assert.ok(!source.includes("firebase-admin")&&!source.includes("runTransaction("));
 assert.ok(!JSON.stringify(stressed).includes("request_12345"));
 assert.ok(!JSON.stringify(stressed).includes("salonA"));
 console.log("PASS Phase 16.17 2000-request monitoring stress, sequential batches, bounded concurrency, failures, disabled bookings");
}
main().catch(e=>{console.error(e);process.exitCode=1;});
