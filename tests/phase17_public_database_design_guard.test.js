"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const source = fs.readFileSync(path.join(root, "functions/index.js"), "utf8");
const design = fs.readFileSync(path.join(root, "docs/phase17-public-database-isolation.md"), "utf8");
const publishStart = source.indexOf("exports.publishBusiness = onCall(");
const unpublishStart = source.indexOf("exports.unpublishBusiness = onCall(", publishStart);
assert.ok(publishStart >= 0 && unpublishStart > publishStart);
const publish = source.slice(publishStart, unpublishStart);
assert.match(publish, /acceptingBookings:\s*false/);
assert.doesNotMatch(publish, /acceptingBookings:\s*true/);
assert.match(publish, /verifiedUser\(request\)/);
assert.match(publish, /validateProfile\(profile, uid\)/);
assert.match(source, /const db = getFirestore\(\)/);
assert.match(design, /Firestore transactions are confined to a single database/);
assert.match(design, /separate explicit approval/);
assert.match(design, /Do not switch `getFirestore\(\)` to the named database globally/);
console.log("PASS PHASE17_PUBLIC_DATABASE_DESIGN_GUARD");
console.log("CURRENT_SINGLE_DATABASE_ARCHITECTURE_NOT_MIGRATED");
console.log("NO_CLOUD_AUTH_NO_DATABASE_CREATION_NO_IAM_CHANGES_NO_DEPLOYMENT_NO_FIRESTORE_WRITES");
