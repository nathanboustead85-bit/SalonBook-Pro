"use strict";
const test=require("node:test"),assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm"),path=require("node:path");
const html=fs.readFileSync(path.join(__dirname,"../web/phase30/booking-30-1.html"),"utf8");
const script=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
test("standalone HTML",()=>assert.match(html,/^<!doctype html>/i));
test("JavaScript syntax valid",()=>new vm.Script(script));
test("Phase 30.1 branding",()=>assert.ok(html.includes("Phase 30.1")));
test("premium teal hero",()=>assert.ok(html.includes("linear-gradient(110deg,#075a55")));
test("Kody Blends demo",()=>assert.ok(html.includes("Kody Blends")));
test("service picker",()=>assert.ok(html.includes('id="services"')));
test("date picker",()=>assert.ok(html.includes('id="dates"')));
test("time picker",()=>assert.ok(html.includes('id="times"')));
test("name field",()=>assert.ok(html.includes('id="customerName"')));
test("email field",()=>assert.ok(html.includes('id="customerEmail"')));
test("optional phone",()=>assert.ok(html.includes('id="customerPhone"')));
test("summary service",()=>assert.ok(html.includes('id="sumService"')));
test("summary duration",()=>assert.ok(html.includes('id="sumDuration"')));
test("summary date",()=>assert.ok(html.includes('id="sumDate"')));
test("summary time",()=>assert.ok(html.includes('id="sumTime"')));
test("summary price",()=>assert.ok(html.includes('id="sumPrice"')));
test("confirmation disabled by default",()=>assert.match(html,/id="confirm"[^>]+disabled/));
test("confirmation preview only",()=>assert.ok(html.includes("No appointment was created.")));
test("no actual booking",()=>assert.ok(html.includes("No booking is created")));
test("no payment taken",()=>assert.ok(html.includes("no payment is taken")));
test("no customer data transmitted",()=>assert.ok(html.includes("no customer information is saved or transmitted")));
test("no Firebase",()=>assert.ok(!/firebaseConfig|firebase\/app|firebase\.firestore/.test(html)));
test("no network APIs",()=>{for(const x of ["fetch(","XMLHttpRequest","WebSocket(","EventSource(","sendBeacon(","<script src="])assert.ok(!html.includes(x),x)});
test("no persistent browser storage",()=>{for(const x of ["localStorage","sessionStorage","indexedDB","document.cookie"])assert.ok(!html.includes(x),x)});
test("no form submission",()=>assert.ok(!/<form\b/i.test(html)));
test("no external stylesheets",()=>assert.ok(!/<link[^>]+stylesheet/i.test(html)));
test("no live booking endpoints",()=>assert.ok(!/https?:\/\/[^"'\s]+\/(bookings|appointments|checkout)/i.test(html)));
test("mobile responsive",()=>assert.ok(html.includes("@media(max-width:760px)")));
test("small Samsung responsive",()=>assert.ok(html.includes("@media(max-width:360px)")));
test("accessible button pressed state",()=>assert.ok(script.includes('setAttribute("aria-pressed"')));
test("confirmation status announced",()=>assert.ok(html.includes('aria-live="polite"')));
test("safe textContent rendering",()=>assert.ok(script.includes(".textContent=")));
test("no dynamic innerHTML",()=>assert.ok(!script.includes(".innerHTML")));
test("date change clears selected time",()=>assert.ok(script.includes("state.time=null")));
test("confirmation clears on changes",()=>assert.ok(script.includes("clearConfirmation();renderAll()")));
test("details required for preview",()=>assert.ok(script.includes("state.time&&validDetails()")));
test("validates name length",()=>assert.ok(script.includes("n.length>=2&&n.length<=80")));
test("validates email shape",()=>assert.ok(script.includes("e.length<=120&&/")));
test("price formatting",()=>assert.ok(script.includes('"£"+n.toFixed(2)')));
test("no real calendar availability claims",()=>assert.ok(html.includes("Illustrative availability")));
test("all demo slots bound to demo date ids",()=>{const ids=[...script.matchAll(/id:"(d\d)"/g)].map(x=>x[1]);assert.deepEqual(ids,["d1","d2","d3","d4"]);for(const id of ids)assert.ok(script.includes('"'+id+'":['))});
test("reduced motion",()=>assert.ok(html.includes("prefers-reduced-motion")));
test("not indexed",()=>assert.ok(html.includes('noindex,nofollow')));
test("no dependencies",()=>assert.ok(!/<script[^>]+src=|<iframe/i.test(html)));
