"use strict";
const assert=require("node:assert/strict");
const {exactDestinationDecision,assertExactDestinationFence}=require("../functions/phase17ExactDestinationGate");
const {exactPublicationIdentity}=require("../functions/phase17ExactPublicationIdentity");
const uid="owner_1",snap=n=>({exists:true,updateTime:{seconds:1763450000,nanoseconds:n}});
const a=exactPublicationIdentity({uid,operation:"unpublish",snapshot:snap(123456001)});
const b=exactPublicationIdentity({uid,operation:"unpublish",snapshot:snap(123456002)});
assert.equal(a.legacyVersion,b.legacyVersion);
assert.equal(exactDestinationDecision({incoming:a,stored:null}).status,"APPLY");
assert.equal(exactDestinationDecision({incoming:a,stored:b}).status,"STALE");
assert.equal(exactDestinationDecision({incoming:b,stored:a}).status,"APPLY");
assert.equal(exactDestinationDecision({incoming:a,stored:a}).status,"ALREADY_APPLIED");
assert.equal(exactDestinationDecision({incoming:a,stored:{...a,digest:"0".repeat(64)}}).status,"REVISION_CONFLICT");
assert.throws(()=>exactDestinationDecision({incoming:a,stored:{publicationVersion:a.legacyVersion}}),/MIGRATION_REQUIRED/);
assert.throws(()=>exactDestinationDecision({incoming:{...a,revision:"invalid"},stored:null}),/INVALID_FULL_PRECISION_REVISION/);
const claim={key:a.key,digest:a.digest,worker:"worker1",generation:1,state:"HELD",expiresAt:2000};
assert.equal(assertExactDestinationFence({identity:a,claim,nowMs:1999}).generation,1);
assert.throws(()=>assertExactDestinationFence({identity:a,claim,nowMs:2000}),/FENCED/);
assert.throws(()=>assertExactDestinationFence({identity:b,claim,nowMs:1999}),/FENCED/);
assert.throws(()=>assertExactDestinationFence({identity:a,claim:{...claim,digest:"0".repeat(64)},nowMs:1999}),/FENCED/);
console.log("PASS PHASE17_EXACT_DESTINATION_GATE: submicrosecond stale rejection, idempotency, migration refusal and claim checks");
console.log("PURE_OFFLINE_POLICY_NOT_AN_ATOMIC_CROSS_DATABASE_WRITER");
