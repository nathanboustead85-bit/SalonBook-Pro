"use strict";
const assert=require("node:assert/strict");
const {SAMPLE,publishedServices,availableSlots,review}=require("../web/phase1238/availabilityPreview");
const q={serviceId:"cut",staffId:"alex",date:"2026-11-20"};
const slots=availableSlots(SAMPLE,q);
assert.deepEqual(publishedServices(SAMPLE).map(x=>x.id),["cut","colour"]);
console.log("PASS only published services visible");
assert.equal(slots.includes("09:00"),true);
assert.equal(slots.includes("09:30"),false);
assert.equal(slots.includes("10:00"),true);
console.log("PASS overlapping appointments excluded");
assert.equal(slots.includes("12:00"),false);
assert.equal(slots.includes("12:30"),false);
console.log("PASS staff break excluded");
assert.equal(slots.includes("14:00"),false);
assert.equal(slots.includes("14:30"),false);
assert.equal(slots.includes("15:00"),true);
console.log("PASS second existing appointment excluded");
assert.equal(slots.includes("16:30"),true);
assert.equal(slots.includes("17:00"),false);
console.log("PASS outside working hours excluded");
assert.deepEqual(availableSlots(SAMPLE,{...q,serviceId:"private"}),[]);
assert.deepEqual(availableSlots(SAMPLE,{...q,staffId:"off"}),[]);
console.log("PASS unpublished service and inactive staff blocked");
assert.deepEqual(availableSlots({...SAMPLE,published:false},q),[]);
assert.deepEqual(availableSlots(SAMPLE,{...q,date:"2026-11-21"}),[]);
console.log("PASS unpublished business and closed day blocked");
const colour=availableSlots(SAMPLE,{...q,serviceId:"colour"});
assert.equal(colour.includes("09:00"),false);
assert.equal(colour.includes("10:00"),true);
console.log("PASS service duration respected");
const ok=review(SAMPLE,{...q,time:"09:00",customerName:"Demo Customer"});
assert.equal(ok.status,"PREVIEW_ONLY");assert.equal(ok.bookingCreated,false);
console.log("PASS valid customer review creates no appointment");
assert.equal(review(SAMPLE,{...q,time:"09:30",customerName:"Demo Customer"}).status,"INVALID_PREVIEW");
assert.equal(review(SAMPLE,{...q,time:"09:00",customerName:"A"}).status,"INVALID_PREVIEW");
console.log("PASS blocked time and invalid name rejected");
assert.deepEqual(availableSlots({...SAMPLE,appointments:[{staffId:"alex",date:q.date,start:"bad",end:"10:00",status:"confirmed"}]},q),[]);
console.log("PASS malformed booking data fails closed");
assert.deepEqual(availableSlots({...SAMPLE,staff:[{...SAMPLE.staff[0],workingHours:{[q.date]:[["09:00","bad"]]}}]},q),[]);
console.log("PASS malformed working hours fail closed");
