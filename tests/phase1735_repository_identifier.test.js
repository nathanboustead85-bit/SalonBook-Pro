"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const {classify}=require("../scripts/phase1735_repository_identifier.js");
const expected="repo:nathanboustead85-bit/SalonBook-Pro:environment:boustio-function-deployment";
const claims={repository:"nathanboustead85-bit/SalonBook-Pro",repository_id:"123456"};
assert(classify(expected,claims).matchNames.includes("EXPECTED_EXACT"));
assert(classify("repo:nathanboustead85-bit/salonbook-pro:environment:boustio-function-deployment",claims).matchNames.includes("EXPECTED_CASE_INSENSITIVE"));
assert(!classify("repo:nathanboustead85-bit/salonbook-pro:environment:boustio-function-deployment",claims).matchNames.includes("EXPECTED_EXACT"));
assert(classify("repo:123456:environment:boustio-function-deployment",claims).matchNames.includes("REPOSITORY_ID"));
assert.equal(classify("repo:another:environment:boustio-function-deployment",claims).matchNames.length,0);
assert.equal(classify("repo:another:environment:boustio-function-deployment",claims).environmentSuffixMatches,true);
assert.equal(classify(null,claims).valid,false);
const y=fs.readFileSync(".github/workflows/boustio-phase-1735-repository-identifier.yml","utf8");
assert.match(y,/environment: boustio-function-deployment/);
assert.match(y,/CLASSIFY_REPOSITORY_ID/);
assert.match(y,/id-token: write/);
assert.match(y,/github\.ref == 'refs\/heads\/milestone-customer-booking-experience'/);
assert.doesNotMatch(y,/gcloud|firebase deploy|google-github-actions\/auth/);
console.log("PASS Phase 17.35 repository identifier and security guard tests");
