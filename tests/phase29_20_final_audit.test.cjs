test("completion summary",()=>assert.ok(html.includes('id="finishedDetails"')));
test("restart confirmation",()=>assert.ok(html.includes('id="restartConfirm"')));
test("confirmation cancel",()=>assert.ok(html.includes('id="cancelRestart"')));
test("restart only after confirmation",()=>assert.ok(js.includes('$("confirmRestart").addEventListener("click"')));
test("offline no network calls",()=>{for(const x of ["fetch(","XMLHttpRequest","WebSocket(","EventSource(","navigator.sendBeacon","<script src="])assert.equal(html.includes(x),false,x)});
test("offline no persistent browser storage",()=>{for(const x of ["localStorage.","sessionStorage.","indexedDB.","caches.open(","document.cookie"])assert.equal(html.includes(x),false,x)});
test("no Firebase SDK",()=>assert.ok(!/firebase\.(auth|firestore|database)|firebase\/app|firebaseConfig/.test(html)));
