test("functional code frozen from Samsung-approved 29.19",()=>assert.equal(js,prevJs));
test("seven step controls",()=>assert.equal((html.match(/<button data-step="/g)||[]).length,7));
test("navigation announcements",()=>assert.ok(html.includes('id="navigationAnnouncement"')));
test("completion meter",()=>assert.ok(html.includes('id="completionProgress"')));
