"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const {shape,classifySettings}=require("../scripts/boustio_identity_root_cause.js");
const repo="nathanboustead85-bit/SalonBook-Pro",env="boustio-function-deployment";
const claims={repository:repo,ref:"refs/heads/milestone-customer-booking-experience",environment:env,repository_id:"123"};
const result=shape("repo:"+repo+"@refs/heads/main:environment:"+env,claims);
assert.equal(result.valid,true);
assert.equal(result.containsAt,true);
assert.equal(result.repositoryPartMatches,true);
assert.equal(shape("repo:other/repo:environment:"+env,claims).repositoryPartMatches,false);
assert.equal(shape("invalid",claims).valid,false);
assert.equal(classifySettings(200,'{"use_default":true}'),"DEFAULT");
assert.equal(classifySettings(200,'{"use_default":false}'),"CUSTOM");
assert.equal(classifySettings(403,""),"HTTP_403");
const y=fs.readFileSync(".github/workflows/boustio-identity-root-cause.yml","utf8");
assert.match(y,/environment: boustio-function-deployment/);
assert.match(y,/INSPECT_IDENTITY_ONCE/);
assert.match(y,/id-token: write/);
assert.match(y,/github\.ref == 'refs\/heads\/milestone-customer-booking-experience'/);
assert.doesNotMatch(y,/gcloud|firebase deploy|google-github-actions\/auth/);
console.log("PASS Boustio consolidated identity diagnostic safeguards");
