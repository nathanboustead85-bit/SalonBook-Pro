"use strict";
const assert=require("node:assert/strict");
const {sealSnapshot,verifySnapshot,rehearseMigration}=require("../functions/migrationRecoveryRehearsal");
const appointments=[{id:"test-a",time:"09:00"},{id:"test-b",time:"11:30"}];
const json=JSON.stringify(appointments);
const sealed=sealSnapshot(json);
assert.deepEqual(verifySnapshot(sealed),appointments);
console.log("PASS original backup checksum verified");
assert.equal(sealed.sha256.length,64);
assert.throws(()=>verifySnapshot({...sealed,json:json+" "}),/integrity mismatch/);
console.log("PASS modified backup rejected");
assert.throws(()=>verifySnapshot({...sealed,sha256:"0".repeat(64)}),/integrity mismatch/);
console.log("PASS forged checksum rejected");
assert.throws(()=>sealSnapshot("{broken"),SyntaxError);
console.log("PASS malformed backup rejected");
assert.throws(()=>verifySnapshot(sealSnapshot(JSON.stringify({wrong:"shape"}))),/booking array/);
console.log("PASS invalid backup structure rejected");
const success=rehearseMigration(sealed);
assert.equal(success.status,"simulated-success");
assert.equal(success.liveBookingsEnabled,false);
assert.deepEqual(success.stagedIds,["test-a","test-b"]);
console.log("PASS full disposable migration simulation");
for(const step of [1,2]){
  const result=rehearseMigration(sealed,{failAfter:step,existingIds:["unrelated"]});
  assert.equal(result.status,"simulated-rollback");
  assert.equal(result.committed,false);
  assert.equal(result.liveBookingsEnabled,false);
  assert.deepEqual(result.stagedIds,["unrelated"]);
  assert.deepEqual(verifySnapshot(sealed),appointments);
  console.log("PASS interruption after record",step,"restores simulated baseline");
}
const duplicate=rehearseMigration(sealSnapshot(JSON.stringify([appointments[0],appointments[0]])));
assert.equal(duplicate.status,"simulated-rollback");
assert.deepEqual(duplicate.stagedIds,[]);
console.log("PASS duplicate appointment rolls back simulation");
const conflict=rehearseMigration(sealed,{existingIds:["test-a"]});
assert.equal(conflict.status,"simulated-rollback");
assert.deepEqual(conflict.stagedIds,["test-a"]);
console.log("PASS existing record is never overwritten");
assert.deepEqual(verifySnapshot(sealed),appointments);
console.log("PASS sealed original remains recoverable");
