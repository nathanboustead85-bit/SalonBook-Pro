"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const {createMultiDeviceRecoveryGuard}=require("../functions/phase1618MultiDeviceRecoveryGuard");
const {prepareBookingStoragePlan}=require("../functions/phase151BookingInfrastructurePreparation");
const {DISABLED}=require("../functions/phase147DisabledAtomicReservation");
const secret="phase1618-server-test-secret-more-than-32";
const input={ownerId:"salonA",key:"request_12345",intent:{serviceId:"cut",staffId:"barber",date:"2026-11-20",time:"10:00"}};
const plan=prepareBookingStoragePlan({...input,secret});
const id="b".repeat(64);
const marker={ownerId:"salonA",requestId:plan.requestId,fingerprint:plan.fingerprint,reservationId:id,state:"COMMITTED_SIMULATION",schemaVersion:1};
const reservation={id,ownerId:"salonA",requestId:plan.requestId,fingerprint:plan.fingerprint,state:"COMMITTED_SIMULATION",schemaVersion:1};
const pair={consistentSnapshot:true,marker,reservation};
async function main(){
 let reads=0,active=0,peak=0;
 const good=createMultiDeviceRecoveryGuard({secret,readConsistentPair:async()=>{
  reads++;active++;peak=Math.max(peak,active);
  await new Promise(resolve=>setImmediate(resolve));active--;return pair;
 }});
 const same=await good.inspect([input,{...input,deviceId:"phone"},{...input,deviceId:"tablet"}]);
 assert.equal(same.status,"MULTI_DEVICE_READ_ONLY_CLEAR");
 assert.equal(same.inspected,3);
 const before=reads;
 const conflict=await good.inspect([input,{...input,deviceId:"tablet",intent:{...input.intent,time:"11:00"}}]);
 assert.equal(conflict.status,"MULTI_DEVICE_MANUAL_REVIEW_REQUIRED");
 assert.equal(conflict.collisions,1);
 assert.equal(conflict.inspected,0);
 assert.equal(reads,before,"conflict must be rejected before any reads");
 const malformed=await good.inspect([input,{...input,key:"bad"}]);
 assert.equal(malformed.invalid,1);
 assert.equal(malformed.inspected,0);
 assert.equal(reads,before);
 const other=await good.inspect([input,{...input,ownerId:"salonB"}]);
 assert.equal(other.collisions,0);
 assert.equal(other.status,"MULTI_DEVICE_MANUAL_REVIEW_REQUIRED","cross-owner records must not verify");
 const flood=await good.inspect(Array.from({length:100},()=>input));
 assert.equal(flood.throttled,90);
 assert.equal(flood.inspected,10);
 assert.equal(flood.status,"MULTI_DEVICE_MANUAL_REVIEW_REQUIRED");
 assert.ok(peak<=5);
 assert.equal((await good.inspect([])).status,"MULTI_DEVICE_INPUT_INVALID");
 assert.equal((await good.inspect(Array.from({length:101},()=>input))).status,"MULTI_DEVICE_INPUT_INVALID");
 assert.equal((await good.inspect("bad")).status,"MULTI_DEVICE_INPUT_INVALID");
 assert.equal((await good.inspect([null])).status,"MULTI_DEVICE_MANUAL_REVIEW_REQUIRED");
 const offline=createMultiDeviceRecoveryGuard({secret,readConsistentPair:async()=>{throw Error("offline");}});
 assert.equal((await offline.inspect([input])).status,"MULTI_DEVICE_MANUAL_REVIEW_REQUIRED");
 const absent=createMultiDeviceRecoveryGuard({secret,readConsistentPair:async()=>({consistentSnapshot:true,marker:null,reservation:null})});
 assert.equal((await absent.inspect([input])).status,"MULTI_DEVICE_READ_ONLY_CLEAR");
 assert.deepEqual(await good.reserve(input),DISABLED);
 const entry=fs.readFileSync(path.join(__dirname,"../functions/index.js"),"utf8");
 const source=fs.readFileSync(path.join(__dirname,"../functions/phase1618MultiDeviceRecoveryGuard.js"),"utf8");
 assert.ok(!entry.includes("phase1618MultiDeviceRecoveryGuard"));
 assert.ok(!source.includes("firebase-admin")&&!source.includes("runTransaction("));
 assert.ok(!JSON.stringify(conflict).includes("request_12345"));
 assert.ok(!JSON.stringify(conflict).includes("salonA"));
 console.log("PASS Phase 16.18 multi-device retry collision, owner isolation, bounded reads, disabled booking");
}
main().catch(e=>{console.error(e);process.exitCode=1;});
