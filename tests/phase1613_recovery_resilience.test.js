"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const {createRecoveryResilienceInspector}=require("../functions/phase1613RecoveryResilienceInspector");
const {prepareBookingStoragePlan}=require("../functions/phase151BookingInfrastructurePreparation");
const {DISABLED}=require("../functions/phase147DisabledAtomicReservation");
const secret="phase1613-server-test-secret-more-than-32";
const input={ownerId:"salonA",key:"request_12345",intent:{serviceId:"cut",staffId:"barber",date:"2026-11-20",time:"10:00"}};
const plan=prepareBookingStoragePlan({...input,secret});
const id="b".repeat(64);
const marker={ownerId:"salonA",requestId:plan.requestId,fingerprint:plan.fingerprint,reservationId:id,state:"COMMITTED_SIMULATION",schemaVersion:1};
const reservation={id,ownerId:"salonA",requestId:plan.requestId,fingerprint:plan.fingerprint,state:"COMMITTED_SIMULATION",schemaVersion:1};
const pair={consistentSnapshot:true,marker,reservation};
const make=readConsistentPair=>createRecoveryResilienceInspector({secret,readConsistentPair});
async function main(){
 const ok=make(async()=>pair);
 assert.equal((await ok.rehearse([input])).status,"REHEARSAL_READ_ONLY_COMPLETE");
 const hundred=await ok.rehearse(Array.from({length:100},()=>input));
 assert.equal(hundred.checked,100);
 assert.equal(hundred.uncertainCount,0);
 assert.equal((await ok.rehearse([])).status,"REHEARSAL_INVALID");
 assert.equal((await ok.rehearse(Array.from({length:101},()=>input))).status,"REHEARSAL_INVALID");
 assert.equal((await ok.rehearse("bad")).status,"REHEARSAL_INVALID");
 const offline=await make(async()=>{throw Error("offline");}).rehearse([input]);
 assert.equal(offline.status,"REHEARSAL_MANUAL_REVIEW_REQUIRED");
 assert.equal(offline.uncertainCount,1);
 assert.equal((await make(async()=>({...pair,marker:null})).rehearse([input])).status,"REHEARSAL_MANUAL_REVIEW_REQUIRED");
 assert.equal((await make(async()=>({...pair,reservation:{...reservation,ownerId:"salonB"}})).rehearse([input])).status,"REHEARSAL_MANUAL_REVIEW_REQUIRED");
 assert.equal((await make(async()=>({...pair,consistentSnapshot:false})).rehearse([input])).status,"REHEARSAL_MANUAL_REVIEW_REQUIRED");
 assert.equal((await make(async()=>({consistentSnapshot:true,marker:null,reservation:null})).rehearse([input])).status,"REHEARSAL_READ_ONLY_COMPLETE");
 assert.equal((await ok.rehearse([{...input,key:"bad"}])).status,"REHEARSAL_MANUAL_REVIEW_REQUIRED");
 assert.deepEqual(await ok.reserve(input),DISABLED);
 const entry=fs.readFileSync(path.join(__dirname,"../functions/index.js"),"utf8");
 const source=fs.readFileSync(path.join(__dirname,"../functions/phase1613RecoveryResilienceInspector.js"),"utf8");
 assert.ok(!entry.includes("phase1613RecoveryResilienceInspector"));
 assert.ok(!source.includes("firebase-admin")&&!source.includes("runTransaction("));
 assert.ok(!JSON.stringify(hundred).includes("request_12345"));
 console.log("PASS Phase 16.13 100-device recovery, interruptions, corruption, owner isolation, outages, no booking writes");
}
main().catch(e=>{console.error(e);process.exitCode=1;});
