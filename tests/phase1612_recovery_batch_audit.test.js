"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const {createRecoveryBatchAuditor}=require("../functions/phase1612RecoveryBatchAuditor");
const {prepareBookingStoragePlan}=require("../functions/phase151BookingInfrastructurePreparation");
const {DISABLED}=require("../functions/phase147DisabledAtomicReservation");
const secret="phase1612-server-test-secret-more-than-32";
const input={ownerId:"salonA",key:"request_12345",intent:{serviceId:"cut",staffId:"barber",date:"2026-11-20",time:"10:00"}};
const plan=prepareBookingStoragePlan({...input,secret});
const id="b".repeat(64);
const marker={ownerId:"salonA",requestId:plan.requestId,fingerprint:plan.fingerprint,reservationId:id,state:"COMMITTED_SIMULATION",schemaVersion:1};
const reservation={id,ownerId:"salonA",requestId:plan.requestId,fingerprint:plan.fingerprint,state:"COMMITTED_SIMULATION",schemaVersion:1};
const good={consistentSnapshot:true,marker,reservation};
async function main(){
 const make=readConsistentPair=>createRecoveryBatchAuditor({secret,readConsistentPair});
 const ok=make(async()=>good);
 assert.equal((await ok.audit([input])).status,"BATCH_REVIEW_COMPLETE");
 const hundred=await ok.audit(Array.from({length:100},()=>input));
 assert.equal(hundred.checked,100);
 assert.equal(hundred.status,"BATCH_REVIEW_COMPLETE");
 assert.equal((await ok.audit([])).status,"BATCH_INVALID");
 assert.equal((await ok.audit(Array.from({length:101},()=>input))).status,"BATCH_INVALID");
 assert.equal((await ok.audit("invalid")).status,"BATCH_INVALID");
 assert.equal((await ok.audit([{...input,key:"bad"}])).status,"BATCH_MANUAL_REVIEW_REQUIRED");
 assert.equal((await make(async()=>({...good,reservation:{...reservation,ownerId:"salonB"}})).audit([input])).status,"BATCH_MANUAL_REVIEW_REQUIRED");
 assert.equal((await make(async()=>({...good,marker:null})).audit([input])).status,"BATCH_MANUAL_REVIEW_REQUIRED");
 assert.equal((await make(async()=>{throw Error("offline");}).audit([input])).status,"BATCH_MANUAL_REVIEW_REQUIRED");
 const none=await make(async()=>({consistentSnapshot:true,marker:null,reservation:null})).audit([input]);
 assert.equal(none.status,"BATCH_REVIEW_COMPLETE");
 assert.deepEqual(await ok.reserve(input),DISABLED);
 const entry=fs.readFileSync(path.join(__dirname,"../functions/index.js"),"utf8");
 const source=fs.readFileSync(path.join(__dirname,"../functions/phase1612RecoveryBatchAuditor.js"),"utf8");
 assert.ok(!entry.includes("phase1612RecoveryBatchAuditor"));
 assert.ok(!source.includes("firebase-admin")&&!source.includes("runTransaction("));
 assert.ok(!JSON.stringify(hundred).includes("request_12345"));
 console.log("PASS Phase 16.12 bounded 100-device read-only audit, corruption, isolation, outage, disabled bookings");
}
main().catch(e=>{console.error(e);process.exitCode=1;});
