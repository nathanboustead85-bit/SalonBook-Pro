"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const {inspectSubject}=require("../scripts/phase1734_subject_structure.js");
const expected="repo:nathanboustead85-bit/SalonBook-Pro:environment:boustio-function-deployment";
const standard=inspectSubject(expected);
assert.equal(standard.standard,true);
assert.equal(standard.prefixClass,"REPO");
assert.equal(standard.repositoryLiteralPresent,true);
assert.equal(standard.environmentLiteralPresent,true);
assert.equal(inspectSubject("repo:other/repo:ref:refs/heads/main").standard,false);
assert.equal(inspectSubject("repository_id:1234:environment:boustio-function-deployment").prefixClass,"REPOSITORY_ID");
assert.equal(inspectSubject("repo:other/repo:job_workflow_ref:owner/repo/.github/workflows/a.yml@main").jobWorkflowRefPresent,true);
assert.equal(inspectSubject("repo:other%2Frepo:environment:foo%3Abar").slashEncodedPresent,true);
assert.equal(inspectSubject(null).valid,false);
const y=fs.readFileSync(".github/workflows/boustio-phase-1734-subject-structure.yml","utf8");
assert.match(y,/environment: boustio-function-deployment/);
assert.match(y,/INSPECT_SUBJECT_STRUCTURE/);
assert.match(y,/id-token: write/);
assert.match(y,/github\.ref == 'refs\/heads\/milestone-customer-booking-experience'/);
assert.doesNotMatch(y,/gcloud|firebase deploy|google-github-actions\/auth/);
console.log("PASS Phase 17.34 subject structure and safety guard tests");
