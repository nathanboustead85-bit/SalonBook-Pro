"use strict";
const assert=require("node:assert/strict");
const {revisionContractFromSnapshot,assertLegacyCompatibleRevision,compareExactSourceRevisions}=require("../functions/phase17PrecisionMigrationGate");
const snap=n=>({exists:true,updateTime:{seconds:1763450000,nanoseconds:n}});
const a=revisionContractFromSnapshot(snap(123456001));
const b=revisionContractFromSnapshot(snap(123456002));
assert.notEqual(a.fullPrecisionRevision,b.fullPrecisionRevision);
assert.equal(a.legacyVersion,b.legacyVersion);
assert.equal(compareExactSourceRevisions(a,b),-1);
assert.equal(compareExactSourceRevisions(b,a),1);
assert.equal(a.legacyRepresentable,false);
assert.throws(()=>assertLegacyCompatibleRevision(a),/FULL_PRECISION_MIGRATION_REQUIRED/);
assert.throws(()=>assertLegacyCompatibleRevision(b),/FULL_PRECISION_MIGRATION_REQUIRED/);
const compatible=revisionContractFromSnapshot(snap(123456000));
assert.equal(compatible.legacyRepresentable,true);
assert.equal(assertLegacyCompatibleRevision(compatible),compatible.legacyVersion);
assert.throws(()=>assertLegacyCompatibleRevision({...compatible,legacyVersion:compatible.legacyVersion+1}),/REVISION_CONTRACT_MISMATCH/);
assert.throws(()=>revisionContractFromSnapshot(snap(-1)),/INVALID_TRUSTED_UPDATE_TIME/);
assert.throws(()=>revisionContractFromSnapshot(snap(1000000000)),/INVALID_TRUSTED_UPDATE_TIME/);
assert.throws(()=>revisionContractFromSnapshot({exists:true,updateTime:{seconds:Number.MAX_SAFE_INTEGER,nanoseconds:0}}),/REVISION_NUMERIC_OVERFLOW/);
console.log("PASS PHASE17_PRECISION_MIGRATION_GATE: exact submicrosecond ordering, legacy collision rejection, mismatch and overflow protection");
console.log("OFFLINE_ONLY_NO_FIREBASE_NO_DEPLOYMENT_NO_LIVE_REVISION_MIGRATION");
